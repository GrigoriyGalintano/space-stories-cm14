using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Client.UserInterface.Systems.Chat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Stories.CustomPhrases;

[GenerateTypedNameReferences]
public sealed partial class CustomPhraseEditWindow : FancyWindow
{
    private static readonly Color CounterOverColor = Color.FromHex("#DD4444");

    private readonly CustomPhrasesUIController _controller;
    private readonly Dictionary<string, Button> _tagButtons = new();
    private readonly int _maxLength;

    public CustomPhrase? Phrase { get; }

    public CustomPhraseEditWindow(CustomPhrasesUIController controller, CustomPhrase? phrase)
    {
        RobustXamlLoader.Load(this);
        _controller = controller;
        _maxLength = IoCManager.Resolve<IUserInterfaceManager>().GetUIController<ChatUIController>().MaxMessageLength;
        Phrase = phrase;

        TextInput.Placeholder = new Rope.Leaf(Loc.GetString("stories-custom-phrases-text-placeholder"));

        if (phrase != null)
        {
            TextInput.TextRope = new Rope.Leaf(phrase.Text);
            TagsEdit.Text = CustomPhrasesUIController.FormatTags(phrase.Tags);

            DeleteButton.Text = Loc.GetString("stories-custom-phrases-delete");
            DeleteButton.ConfirmationText = Loc.GetString("stories-custom-phrases-delete-confirm");
            DeleteButton.Visible = true;
            DeleteButton.OnPressed += _ =>
            {
                _controller.Remove(phrase);
                Close();
            };
        }

        TextInput.OnTextChanged += _ => UpdateCounter();
        TagsEdit.OnTextChanged += _ => UpdateTagButtons();
        TagsEdit.OnTextEntered += _ => Submit();
        SaveButton.OnPressed += _ => Submit();
        CancelButton.OnPressed += _ => Close();

        CreateTagButtons();
        UpdateCounter();
    }

    private string GetText()
    {
        return Rope.Collapse(TextInput.TextRope)
            .Replace("\r", " ")
            .Replace("\n", " ")
            .Trim();
    }

    private void UpdateCounter()
    {
        var length = GetText().Length;
        CounterLabel.Text = $"{length} / {_maxLength}";
        CounterLabel.FontColorOverride = length > _maxLength ? CounterOverColor : null;
    }

    private void CreateTagButtons()
    {
        var tags = _controller.AllTags();
        KnownTagsContainer.Visible = tags.Count > 0;

        foreach (var tag in tags)
        {
            var button = new Button
            {
                Text = $"#{tag}",
                ToggleMode = true,
                StyleClasses = { StyleBase.ButtonOpenBoth },
            };

            button.OnToggled += args => ToggleTag(tag, args.Pressed);
            _tagButtons[tag] = button;
            KnownTagsContainer.AddChild(button);
        }

        UpdateTagButtons();
    }

    private void ToggleTag(string tag, bool enabled)
    {
        var tags = _controller.ParseTags(TagsEdit.Text);

        if (enabled && !tags.Contains(tag))
            tags.Add(tag);
        else if (!enabled)
            tags.Remove(tag);

        TagsEdit.Text = CustomPhrasesUIController.FormatTags(tags);
        UpdateTagButtons();
    }

    private void UpdateTagButtons()
    {
        var tags = _controller.ParseTags(TagsEdit.Text);

        foreach (var (tag, button) in _tagButtons)
        {
            button.Pressed = tags.Contains(tag);
        }

        var count = _controller.CountTagsWith(Phrase, tags);
        TagsCounterLabel.Text = $"{count} / {_controller.MaxTags}";
        TagsCounterLabel.FontColorOverride = count > _controller.MaxTags ? CounterOverColor : null;
    }

    private void Submit()
    {
        var text = GetText();
        if (text.Length == 0)
        {
            ShowError(Loc.GetString("stories-custom-phrases-error-empty"));
            return;
        }

        if (text.Length > _maxLength)
        {
            ShowError(Loc.GetString("stories-custom-phrases-error-too-long", ("max", _maxLength)));
            return;
        }

        var tags = _controller.ParseTags(TagsEdit.Text);

        if (_controller.CountTagsWith(Phrase, tags) > _controller.MaxTags)
        {
            ShowError(Loc.GetString("stories-custom-phrases-error-tags-limit", ("max", _controller.MaxTags)));
            return;
        }

        if (Phrase != null)
        {
            _controller.Update(Phrase, text, tags);
        }
        else if (!_controller.TryAdd(text, tags))
        {
            ShowError(Loc.GetString("stories-custom-phrases-error-limit", ("max", _controller.MaxPhrases)));
            return;
        }

        Close();
    }

    private void ShowError(string message)
    {
        ErrorLabel.Text = message;
        ErrorLabel.Visible = true;
    }
}
