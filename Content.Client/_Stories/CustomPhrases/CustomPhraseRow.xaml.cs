using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Stories.CustomPhrases;

[GenerateTypedNameReferences]
public sealed partial class CustomPhraseRow : BoxContainer
{
    private const int PreviewLength = 160;

    public event Action? OnSend;
    public event Action? OnEdit;

    public bool SendDisabled
    {
        get => SendButton.Disabled;
        set => SendButton.Disabled = value;
    }

    public CustomPhraseRow()
    {
        RobustXamlLoader.Load(this);

        SendButton.OnPressed += _ => OnSend?.Invoke();
        EditButton.OnPressed += _ => OnEdit?.Invoke();
    }

    public void SetPhrase(CustomPhrase phrase)
    {
        var preview = phrase.Text.Length > PreviewLength
            ? phrase.Text[..PreviewLength].TrimEnd() + "..."
            : phrase.Text;

        TextLabel.SetMessage(FormattedMessage.FromUnformatted(preview));

        TagsLabel.Text = CustomPhrasesUIController.FormatTags(phrase.Tags);
        TagsLabel.Visible = phrase.Tags.Count > 0;
    }
}
